# 雜湊自動跟著內容走，改一個字就變。
def rule_version() -> str:
    """回傳目前 SYSTEM_PROMPT 內容雜湊的前 12 碼，作為規則版本識別。

    只取前 12 碼是因為這是人要看的識別碼（會出現在報表與查詢結果裡），
    碰撞風險在單一專案的 prompt 版本數量級下可忽略。
    """
    import hashlib

    return hashlib.sha256(SYSTEM_PROMPT.encode("utf-8")).hexdigest()[:12]
